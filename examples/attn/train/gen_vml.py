#!/usr/bin/env python3
"""train_step.vml text generator (imported by make_attn_train.py).

ASCII-only on purpose: the .vml must be valid UTF-8 for the assembler.
"""

T, D, NH, HD, F, V = 4, 8, 1, 8, 16, 8

# Trainable params. Order == constant registration order == torch grad concat order.
NAME_ORDER = [
    "Wqkv", "bqkv", "Wproj", "bproj",
    "W1", "b1", "W2", "b2",
    "ln1_g", "ln1_b", "ln2_g", "ln2_b", "lnf_g", "lnf_b",
    "E", "pos",
]


def gen_vml():
    """Return the full text of train_step.vml."""
    L = []
    A = L.append

    A("; P8 member F: Transformer training loop (T=4 D=8 NH=1 HD=8 F=16 V=8)")
    A("; Forward math follows examples/attn/block.vml; backward + AdamW are new here.")
    A("; Generated by examples/attn/train/gen_vml.py -- do not hand-edit.")
    A(";")
    A("; Layout decisions:")
    A(";   GEMM default is NT: C[M,N] = A[M,K]*B[N,K]^T, output width N = B.rows.")
    A(";   Attention y = att*V is naturally NN.  P7 fixed an nn bug (under NN the")
    A(";   width must come from B.cols), and block.vml only ever exercised it on a")
    A(";   square vh.  Here T=4 and HD=8 differ, so we take the task's advice and")
    A(";   use TRANSPOSE + default NT instead -- never touching nn:")
    A(";       Vt[HD,T] = TRANSPOSE(V)")
    A(";       y[M,HD]  = att[M,T] * Vt[HD,T]^T        <- plain NT")
    A(";   Backward mirrors it: datt = dy*V, dVt += datt^T*dy; shapes line up.")
    A(";")
    A(";   LN_BWD takes dg as its 4th operand and expects db in the slot right")
    A(";   after it (contract 2.2 + asm/src/main.rs), so dln*_g / dln*_b must be")
    A(";   declared as an adjacent pair with nothing in between.")
    A("")
    A("    ; ===================== forward =====================")
    A("    ; --- slot-table ordering (LN_BWD addressing) ---")
    A("    ; LN_BWD dx, dy, x, <gslot>  reads gamma = slot[gslot] and writes")
    A("    ;   dgamma -> slot[gslot+1],  dbeta -> slot[gslot+2],")
    A("    ; addressing both by SLOT NUMBER.  The assembler hands out slot")
    A("    ; numbers in first-mention order, so the three names must be first")
    A("    ; mentioned consecutively, in that order.")
    A("    ; SHAPE is a load-time meta instruction (zero runtime cost, and")
    A("    ; force_shape skips Const slots), so it is a safe way to pin the")
    A("    ; numbering without touching any data.")
    for base in ["ln1", "ln2", "lnf"]:
        A(f"    SHAPE       {base}_g, 1, {D}")
        A(f"    SHAPE       g_{base}_g, 1, {D}")
        A(f"    SHAPE       g_{base}_b, 1, {D}")
    A("")
    A(f"    SHAPE       x,        {T}, {D}")
    A("    ; x = tok_emb + pos -- per-position EMB lookup so E gets a gradient.")
    A("    ; CONCAT joins along COLUMNS, so stacking rows needs a transpose each:")
    A("    ;   row r:  e_r[1,D] -> TRANSPOSE -> [D,1]  (a column)")
    A("    ;   CONCAT the columns -> [D,T] -> TRANSPOSE -> [T,D]")
    for r in range(T):
        A(f"    SHAPE       e{r}, 1, {D}")
        A(f"    EMB         e{r}, E, tokr{r}")
        A(f"    SHAPE       e{r}t, {D}, 1")
        A(f"    TRANSPOSE   e{r}t, e{r}")
    A(f"    SHAPE       embT01, {D}, 2")
    A("    CONCAT      embT01, e0t, e1t")
    A(f"    SHAPE       embT23, {D}, 2")
    A("    CONCAT      embT23, e2t, e3t")
    A(f"    SHAPE       embT, {D}, {T}")
    A("    CONCAT      embT, embT01, embT23")
    A(f"    SHAPE       emb, {T}, {D}")
    A("    TRANSPOSE   emb, embT")
    A("    COPY        x, emb")
    A("    EWADD       x, x, pos")
    A("    COPY        x0, x                   ; snapshot after embedding (LN1 bwd)")
    A("")
    A("    ; ---- multi-head attention (NH=1, so one head) ----")
    A("    LN          xd, x, ln1_g, ln1_b")
    A(f"    GEMM        qkv, xd, Wqkv           ; [{T},{3 * D}]")
    A("    BIAS        qkv, bqkv")
    A(f"    SLICE       qc, qkv, 0, {D}")
    A(f"    SLICE       kc, qkv, {D}, {D}")
    A(f"    SLICE       vc, qkv, {2 * D}, {D}")
    A(f"    GEMM        att, qc, kc             ; S = Q*K^T   [{T},{T}]")
    A("    SCALE       att, att, inv_sqrt_hd")
    A("    SOFTMAX     att, att, causal")
    A(f"    TRANSPOSE   vt, vc                  ; [{D},{T}]")
    A(f"    GEMM        y, att, vt              ; y[{T},{D}] via NT")
    A("")
    A("    ; ---- output projection + residual ----")
    A("    GEMM        proj, y, Wproj")
    A("    BIAS        proj, bproj")
    A("    COPY        x1, x                    ; residual bypass snapshot")
    A("    EWADD       x, x, proj")
    A("")
    A("    ; ---- FFN ----")
    A("    LN          xh, x, ln2_g, ln2_b")
    A(f"    GEMM        hpre, xh, W1            ; [{T},{F}]")
    A("    BIAS        hpre, b1")
    A("    ACT         h, hpre, relu")
    A("    GEMM        ff, h, W2")
    A("    BIAS        ff, b2")
    A("    COPY        x2, x                    ; residual bypass snapshot")
    A("    EWADD       x, x, ff")
    A("")
    A("    ; ---- output head ----")
    A("    LN          xf, x, lnf_g, lnf_b")
    A(f"    GEMM        logits, xf, E           ; [{T},{V}]")
    A("")
    A("    ; ===================== backward =====================")
    A("    ; param grads accumulate in the grad region -> zero them each step")
    for n in NAME_ORDER:
        A(f"    ZERO        g_{n}")
    A("")
    A("    ; ---- per-position cross entropy ----")
    A("    ; OP_CE_BWD is single-sample: it flattens its logits operand and takes")
    A("    ; ONE scalar target.  So we run it once per position on a [1,V] row")
    A("    ; slice, and stitch the rows back together.")
    A("    ; Row r of logits -> [V,1]:  TRANSPOSE to [V,T] then SLICE column r.")
    A("    ; We keep dlogits in [V,T] layout and use WRITECOL to drop each")
    A("    ; position's gradient in as a SINGLE column (width 1 -- WRITECOL")
    A("    ; copies `src.cols` entries per row from column `off`, so the source")
    A("    ; must be exactly as wide as the slice it lands in).")
    A(f"    SHAPE       logitsT, {V}, {T}")
    A("    TRANSPOSE   logitsT, logits")
    A(f"    SHAPE       dlogitsT, {V}, {T}")
    A("    ZERO        dlogitsT")
    for r in range(T):
        A(f"    SHAPE       lgT{r}, {V}, 1")
        A(f"    SLICE       lgT{r}, logitsT, {r}, 1")
        A(f"    SHAPE       dlT{r}, {V}, 1")
        A(f"    CE_BWD      lgT{r}, dlT{r}, tgt{r}    ; loss of position {r} -> vm.loss")
        A(f"    WRITECOL    dlogitsT, dlT{r}, {r}      ; dlogitsT[:,{r}] = grad of row {r}")
    A("    ; NOTE: OP_CE_BWD overwrites vm.loss each call, so vm.loss holds the")
    A("    ; LAST position's CE.  The driver recomputes the T-position mean loss")
    A("    ; from `logits` itself so the reported curve uses one consistent")
    A("    ; definition (same loss whose gradient we backpropagate).")
    A(f"    SHAPE       dlogits, {T}, {V}")
    A("    TRANSPOSE   dlogits, dlogitsT")
    A("    ; torch's cross_entropy over [T,V] logits with [T] targets takes the")
    A("    ; MEAN, while our per-position CE_BWD produces the SUM.  Scale by 1/T")
    A("    ; so the analytic gradient is directly comparable to torch's.")
    A(f"    SHAPE       inv_t, 1, 1")
    A("    SCALE       dlogits, dlogits, inv_t")
    A("")
    A("    ; ---- head backward: logits = xf*E^T ----")
    A("    GEMM_BWD_W  g_E, dlogits, xf         ; dE  += dlogits^T*xf")
    A(f"    SHAPE       dxf, {T}, {D}")
    A("    GEMM_BWD_X  dxf, dlogits, E          ; dxf = dlogits*E")
    A(f"    SHAPE       dx, {T}, {D}")
    A("    ; LN_BWD: 4 operands -> dx, dy, x, <gslot>")
    A("    ;   gamma = slot[gslot],  dgamma -> slot[gslot+1],  dbeta -> slot[gslot+2]")
    A("    ; The forward section pinned (lnf_g, g_lnf_g, g_lnf_b) to contiguous")
    A("    ; slot numbers, so naming lnf_g here lands the two grads correctly.")
    A("    LN_BWD      dx, dxf, x, lnf_g")
    A("")
    A("    ; ---- FFN backward (residual: both paths carry gradient) ----")
    A("    GEMM_BWD_W  g_W2, dx, h")
    A("    BIAS_BWD    g_b2, dx")
    A(f"    SHAPE       dh, {T}, {F}")
    A("    GEMM_BWD_X  dh, dx, W2")
    A(f"    SHAPE       dhpre, {T}, {F}")
    A("    ACT_BWD     dhpre, dh, hpre, relu")
    A("    GEMM_BWD_W  g_W1, dhpre, xh")
    A("    BIAS_BWD    g_b1, dhpre")
    A(f"    SHAPE       dxh, {T}, {D}")
    A("    GEMM_BWD_X  dxh, dhpre, W1")
    A(f"    SHAPE       dx2, {T}, {D}")
    A("    LN_BWD      dx2, dxh, x2, ln2_g")
    A("    EWADD       dx, dx, dx2              ; residual grad adds back")
    A("")
    A("    ; ---- attention backward ----")
    A("    GEMM_BWD_W  g_Wproj, dx, y")
    A("    BIAS_BWD    g_bproj, dx")
    A(f"    SHAPE       dy, {T}, {D}")
    A("    GEMM_BWD_X  dy, dx, Wproj")
    A("")
    A("    ; datt[M,T] = dy[M,HD] * V[T,HD]^T")
    A("    ; GEMM_BWD_X cannot express this: its kernel indexes w[j][p] with")
    A("    ;   j < n = dy.cols and p < k = w.rows, so it needs w's row stride")
    A("    ;   to equal w.rows -- only true for a square w.  With T != HD a")
    A("    ;   [T,HD] or [HD,T] w reads out of bounds.")
    A("    ; So transpose the whole product and use GEMM_BWD_W:")
    A("    ;   datt^T[T,M] = V[T,HD] * dy[M,HD]^T")
    A("    ;   GEMM_BWD_W dW[N,K] += A[i,N]^T * X[i,K]  with")
    A("    ;     A = vt [HD,T]  ->  A[i,n] = V[n,i]")
    A("    ;     X = dyT[HD,M]  ->  X[i,k] = dy[k,i]")
    A("    ;   => dW[n,k] = sum_i V[n,i]*dy[k,i] = datt^T   OK")
    A(f"    SHAPE       dattT, {T}, {T}")
    A(f"    SHAPE       dyT, {D}, {T}")
    A(f"    SHAPE       datt, {T}, {T}")
    A("    ZERO        dattT")
    A("    TRANSPOSE   dyT, dy")
    A("    GEMM_BWD_W  dattT, vt, dyT")
    A("    TRANSPOSE   datt, dattT")
    A("")
    A("    ; dV[T,HD] += att[M,T]^T * dy[M,HD]  -- GEMM_BWD_W (accumulate).")
    A("    ;   NOTE: the operand is **att**, not datt.  y = att*V^T means")
    A("    ;   y[i,n] = sum_j att[i,j]*V[j,n], so dV[j,n] = sum_i att[i,j]*dy[i,n]")
    A("    ;   = att^T * dy.  Using datt here is the classic attention-backward bug.")
    A(f"    SHAPE       dvc, {T}, {D}")
    A("    ZERO        dvc")
    A("    GEMM_BWD_W  dvc, att, dy")
    A("")
    A("    ; att = softmax(S, causal) -> dS  (**must pass causal** or grad leaks)")
    A(f"    SHAPE       dS, {T}, {T}")
    A("    SOFTMAX_BWD dS, datt, att, causal")
    A("    SCALE       dS, dS, inv_sqrt_hd      ; S = QK^T/sqrt(hd)")
    A("")
    A("    ; S = Q*K^T -> dQ = dS*K,  dK += dS^T*Q")
    A("    ; GEMM_BWD_X computes dx = dy * w with w treated as [N,K] and")
    A("    ;   k forced to w.rows -- so it can only express dy*w^T (= NT).")
    A("    ; dS*K is a plain NN product, so route dQ through GEMM_BWD_W:")
    A("    ;   GEMM_BWD_W dW[N,K] += dy[M,N]^T * x[M,K]")
    A("    ;   dy = dS^T, x = K  ->  dW[T,D] += dS * K                = dQ")
    A("    ;   dy = dS,   x = Q  ->  dW[T,D] += dS^T * Q              = dK")
    A("    ; Both accumulate, so zero the targets first.")
    A(f"    SHAPE       dq, {T}, {D}")
    A(f"    SHAPE       dk, {T}, {D}")
    A(f"    SHAPE       dSt, {T}, {T}")
    A("    ZERO        dq")
    A("    ZERO        dk")
    A("    TRANSPOSE   dSt, dS")
    A("    GEMM_BWD_W  dq, dSt, kc              ; dq += dS*kc")
    A("    GEMM_BWD_W  dk, dS, qc               ; dk += dS^T*qc")
    A("")
    A("    ; stitch Q/K/V back into dqkv (column order must match forward: q|k|v)")
    A(f"    SHAPE       dqk, {T}, {2 * D}")
    A("    CONCAT      dqk, dq, dk")
    A(f"    SHAPE       dqkv, {T}, {3 * D}")
    A("    CONCAT      dqkv, dqk, dvc")
    A("")
    A("    ; qkv = xd*Wqkv^T + bqkv")
    A("    GEMM_BWD_W  g_Wqkv, dqkv, xd")
    A("    BIAS_BWD    g_bqkv, dqkv")
    A(f"    SHAPE       dxd, {T}, {D}")
    A("    GEMM_BWD_X  dxd, dqkv, Wqkv")
    A(f"    SHAPE       dx1, {T}, {D}")
    A("    LN_BWD      dx1, dxd, x0, ln1_g")
    A("    EWADD       dx, dx, dx1              ; residual grad adds back")
    A("")
    A("    ; ---- embedding backward ----")
    A("    ; x = emb + pos -> demb = dx, dpos = dx")
    A("    ; Row r of dx: TRANSPOSE to [D,T], SLICE out column r -> [D,1],")
    A("    ; TRANSPOSE back to [1,D].  The engine only has column slice, so a row")
    A("    ; slice costs two transposes.")
    A(f"    SHAPE       demb, {V}, {D}")
    A(f"    SHAPE       dpos, {T}, {D}")
    A("    ZERO        demb")
    A("    ZERO        dpos")
    A(f"    SHAPE       dxt, {D}, {T}")
    A("    TRANSPOSE   dxt, dx                  ; [D,T]")
    for r in range(T):
        A(f"    SHAPE       dxtc{r}, {D}, 1")
        A(f"    SLICE       dxtc{r}, dxt, {r}, 1     ; row {r} of dx, standing up")
        A(f"    SHAPE       dxr{r}, 1, {D}")
        A(f"    TRANSPOSE   dxr{r}, dxtc{r}          ; back to [1,D]")
        A(f"    EMB_BWD     demb, dxr{r}, tokr{r}    ; demb[tok[{r}]] += dx[{r}]")
    for r in range(T):
        A(f"    EMB_BWD     dpos, dxr{r}, posr{r}    ; dpos[{r}] += dx[{r}]")
    A("    ; fold the activation-slot gradients into the real grad region.")
    A("    ; `E` is used twice (output head AND token embedding table), so its")
    A("    ; two contributions must be summed: g_E already holds the head part")
    A("    ; from GEMM_BWD_W above, demb holds the embedding part.")
    A("    EWADD       g_E, g_E, demb")
    A("    EWADD       g_pos, g_pos, dpos")
    A("")
    A("    ; ---- AdamW in place on the constant pool (no recompile, whitepaper 4.3) ----")
    for n in NAME_ORDER:
        A(f"    ADAMW       {n}, g_{n}, hparams")
    A("    HALT")

    return "\n".join(L) + "\n"
