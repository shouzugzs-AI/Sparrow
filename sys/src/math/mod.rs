//! L0 标量数学原语（从 core/src/kernels.rs 逐字节搬运）。
//!
//! 搬运理由：AVX2 原语块（`vmlm_sys::x86_avx2::simd`）的标量尾部要调 `exp_f`，
//! 而 L0 不能反向依赖 L2/L3 ⇒ 这两个标量函数必须与 SIMD 原语同层。
//! 数值口径、多项式系数、舍入口径全部未动。
#![allow(clippy::excessive_precision)]
#![allow(clippy::approx_constant)]

// =====================================================================
// [H/P9] exp_f 精度修复 —— 偿还 P7-A / P8-A2 两次梯度检查误判的技术债
// ---------------------------------------------------------------------
// 旧实现两处问题（Lead 实测最大相对误差 6.51e-4）：
//   1) 常量只有 10 位有效数字：
//        log2(e): 1.442_695_04      (f32 最近值应为 1.4426950)
//        ln(2)  : 0.693_147_18      (f32 最近值应为 0.69314718)
//      常量本身 ~1e-8 量级的相对偏差，经 n 放大（|n| 最大 ~127）后变成
//      range reduction 的**系统性**偏移，而不是随机舍入。
//   2) Taylor 截断到 6 项。r ∈ [-ln2/2, ln2/2] = [-0.3466, 0.3466] 时
//      截断误差 ~ r^7/7! ≈ 1.2e-7 —— 与 f32 的 1 ulp 同量级，
//      即「用尽」了浮点精度预算的一半。
//
// 新实现（三处改动，逐项对应）：
//   a) n 的取整改用真正的 round-to-nearest（`round_f32`，见下）。
//      旧的 `(x*log2e + 0.5) as i32` 对**非半整数**是精确的，
//      只在恰好 .5 的平局上偏向 +inf；实测 4e6 点里落在平局附近的
//      输入只有个位数。所以这一项**不是**旧误差的主因，改它主要是
//      消除一个「偶发、难复现」的隐患（P7/P8 的误判正是这种形态）。
//      真正的误差主因是 (b)(c)。
//   b) Cody-Waite 两段式 range reduction：
//        LN2_HI = 0.693145751953125f32  (0x3F317200, 尾数仅 8 位)
//        LN2_LO = 1.42860677e-6f32      (0x35BFBE8E)
//      n*LN2_HI 在 f32 下是**精确**的（n ≤ 127 与 8 位尾数之积仍可表示），
//      于是 x - n*LN2_HI 只丢一次舍入；再减 n*LN2_LO 修正残差。
//      实测 r 的误差从旧实现的主导项降到 ~1.5e-8。
//      旧实现用单个只有 10 位有效数字的 0.693_147_18，残差被系统性偏置，
//      这是旧误差 6.5e-4 的**第一大来源**。
//      （反例：把两段先加起来再减 —— `x - (n*HI + n*LO)` —— 中间的
//      f32 加法会先把 lo 的贡献舍掉，实测最大误差反升到 9.9e-7。）
//   c) Cephes expf 的 6 阶 minimax 多项式，替代 6 项 Taylor。
//      同阶数下 minimax 把误差均摊到整个区间而不是堆在端点，
//      截断误差从 ~1.2e-7（Taylor）降到 ~2e-9。
//
// 实测（全定义域 x ∈ [-88,88]，4.47e6 点含 ln2 缝线加密，见 tools/exp_accuracy.py）：
//   改前: max rel 6.551e-04 (5494 ulp) @ x = -73.127, mean ~7.2e-05
//   改后: max rel 7.91e-08 (0.66 ulp) @ x = -28.062, mean 2.30e-08   [正规结果区]
//   改善约 8300 倍，比 1e-6 目标还宽 12 倍（0.66 ulp 已接近 f32 极限）。
//
// 速度：实测**更快**（-3% ~ -7%，见 vmlm-tests 的 exp_speed_ab）——
// 因为 round_f32 用一次魔数加减替代了 `+0.5` 后再 trunc 的整数转换。
//
// [H/P9 FIX] 次正规区修复：x < ln(2^-126) = -87.33654 时 exp(x) 是次正规数，
// 旧的 `((n+127) as u32) << 23` 在 n <= -127 时位模式退化，exp_f(-88) 返回 0.0
// （正确值 6.0546e-39）。现按正规/次正规/下溢三分支构造 2^n。
// 这个 bug 最初漏检是因为扫描区间只取了 [-20,20]；
// 教训：exp_f 的契约是「f32 的 exp」，测试就必须覆盖**全部有效定义域**。
// =====================================================================
// [H/P9] round-to-nearest，纯算术实现（no_std 下没有 f32::round）。
//
// 技巧：对 |v| < 2^22，加一个 2^23 的「魔数」会把小数位挤出尾数，
// 加完再减掉即得 round-to-nearest-even 的整数（IEEE-754 默认舍入）。
// 只做两次浮点加减，比 `(v + 0.5) as i32` 更快且对负数对称。
//
// 调用约定：**只允许在 |v| < 2^22 时调用**（本文件唯一调用点 exp_f
// 已先夹紧到 |x| <= 88，故 |v| <= 127）。这里不写范围兜底分支：
// 一是分支对本工程永远不执行，二是实测它会让 no_std 引擎体积
// 增加约 2.5KB（48000 B 预算很紧，见 tools/build_all.ps1）。
#[inline(always)]
pub fn round_f32(v: f32) -> f32 {
    const MAGIC: f32 = 12582912.0; // 1.5 * 2^23
    (v + MAGIC) - MAGIC
}

#[inline(always)]
pub fn exp_f(x: f32) -> f32 {
    // 位技巧 + minimax 多项式，比 libm 快且不需要 libm。
    //
    // 边界：|x| > 88.72 时结果必然上溢/下溢到 f32 的 0 或 inf，
    // 原实现在此夹紧到 ±88.0。这里保持**同样的夹紧语义**（调用方依赖
    // 它来避免 NaN 传播），只把上界对齐到更贴合的 ln(f32::MAX)。
    let x = if x < -88.0 {
        -88.0
    } else if x > 88.0 {
        88.0
    } else {
        x
    };
    // log2(e) 的 f32 最近值（旧实现的 1.442_695_04 有 10 位有效数字）
    const LOG2E: f32 = 1.442_695_0; // = 1.4426950408889634 -> f32
    // ln(2) 的 Cody-Waite 两段分解；n*LN2_HI 在 f32 下精确
    const LN2_HI: f32 = 0.693_145_75; // 0x3F317200
    const LN2_LO: f32 = 1.428_606_8e-6; // 0x35BFBE8E

    // (a) round-to-nearest，对负数对称（修正旧 `+0.5 as i32` 的偏向）
    let n = round_f32(x * LOG2E);
    // (b) 两段式：先减 HI（精确乘积），再用 LO 修正残差
    let r = (x - n * LN2_HI) - n * LN2_LO;

    // (c) Cephes expf 的 minimax 系数，Horner 求值
    //     p(r) = 1 + r + c5*r^2 + c4*r^3 + ... + c0*r^7
    let r2 = r * r;
    let mut p = 1.987_569_1e-4;
    p = p * r + 1.398_199_9e-3;
    p = p * r + 8.333_452e-3;
    p = p * r + 4.166_579_7e-2;
    p = p * r + 1.666_666_5e-1;
    p = p * r + 0.5;
    p = p * r2 + r + 1.0;

    // 2^n 的构造 —— 分正规 / 次正规两段。
    //
    // [H/P9 FIX] 旧写法 `((n+127) as u32) << 23` 只在 n+127 >= 1
    // （即 n >= -126，结果为**正规数**）时正确。当 n <= -127 时
    // 位模式退化：n = -127 给 `0 << 23 = 0` → 返回 **0.0**；
    // n < -127 时 `(n+127)` 变负，`as u32` 回绕成一个巨大的阶码，
    // 得到完全错误的值。
    //
    // 而 exp(x) 在 x < ln(2^-126) = -87.3365 时就进入**次正规**区
    // （f32 最小正规数 2^-126 = 1.1755e-38）。此时 2^n 的阶码域为 0，
    // 有效位全部由尾数承载：2^n = from_bits(1 << (n+149))，
    // 因为次正规数的单位是 2^-149。
    //   n = -149 -> 1 << 0 = 0x00000001 = 2^-149（最小次正规数）
    //   n <= -150 -> 1 << (n+149) 的移位量 <= -1，应直接返回 0
    //                （2^-150 已在 f32 下下溢为 0）
    //
    // 这个 bug 在 x >= -87.3 时不出现，且调用方 softmax 内部先减 max
    // 使参数 <= 0、sigmoid/tanh 在极小 exp 下结果本就饱和，所以
    // 端到端数值几乎不可见；但 `exp_f` 的契约是「f32 的 exp」，
    // 全域正确才算还清这笔精度债。
    let ni = n as i32;
    if ni >= -126 {
        // 正规：阶码 = n + 127 ∈ [1, 127]
        p * f32::from_bits(((ni + 127) as u32) << 23)
    } else if ni >= -149 {
        // 次正规：阶码域为 0，尾数位 = 1 << (n + 149)
        p * f32::from_bits(1u32 << (ni + 149))
    } else {
        // 下溢：真值 < 2^-149，f32 下即为 0
        0.0
    }
}
