#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
P15 S5-W1: give the neuron_kv_offsets section a PRODUCER, and put it on disk.

THE GAP THIS FILE CLOSES (quoted, not paraphrased)
--------------------------------------------------
`docs/P14_verification.md` section 3 lists, as explicitly UNVERIFIED:

    S5 端到端作用于真实 24 层引擎 | UNVERIFIED | S5 模块当前没有任何调用方 ...
    Lead 已确认没有任何代码 materialize 该模块的缓冲。

and `docs/P14_S5_O6_报告.md` section 9.1 names the same gap from the other side:
the neuron index exists as an API (`neuron_kv::write_section` / `read_section`)
and as constants (`format.rs`: SEC_NEURON_KV / NKV_HDR / NKV_ENTRY), but

    NOTHING EVER WRITES THE SECTION.

So the "index is not on disk" claim is literally true: there is no producer. This
tool is that producer. It emits the section as real bytes in a real file, then
RE-READS THOSE BYTES BACK FROM DISK and checks them.

WHAT IS *NOT* CLAIMED HERE
--------------------------
* This is HOST-SIDE tooling. It costs the ENGINE **0 bytes**. Nothing in
  `core/src`, `asm/src`, `runtime/src` is touched or linked. (The neuron-kv
  module is feature-gated off by default anyway; but even with the feature ON
  this tool adds nothing to the engine, because it is Python.)
* This does NOT make S5 end-to-end. It closes ONE of the four UNVERIFIED items:
  "the index exists on disk". The engine still does not consume it (no
  load-time reorder call site), and that remains UNVERIFIED. See FINAL VERDICT.
* The 24596 B / 6144-neuron numbers are ARITHMETIC on the shipped formulas, plus
  the byte length of a file this tool actually wrote and stat()ed. They are not a
  measurement of an engine allocation -- no path allocates the neuron-major
  buffer. `p14_s5_layout_lib.py` is where the address-level layout was measured;
  this file deliberately does not re-litigate that.

THE DISCIPLINE THIS FILE OBEYS (docs/P14_verification.md section 0.1)
---------------------------------------------------------------------
Every acceptance assertion is paired with a PERTURBATION that must make it FAIL,
and the counts are printed. The trap being avoided is documented in
`docs/P13_报告.md` section 3.2: a probe whose patch was EMPTY reported "0 B" for a
change that really cost 3584 B. A check that cannot fail is not a measurement.

The three required controls, each reporting a COUNT and not a boolean:

  (a) entry[i] = i * head_dim * stride   (the 128x S5-A bug, re-injected into
      the emitted bytes)  -> the consistency check must report FAIL with a
      nonzero mismatch count.
  (b) the `stride` header field flipped  -> parse-back must FAIL.
  (c) the file truncated by 4 bytes      -> the read must HARD-FAIL (raise),
      not silently shorten to a valid-looking smaller section.

WHY THE BYTES ARE NOT GENERATED BY re-IMPLEMENTING THE FORMAT FROM SCRATCH
-------------------------------------------------------------------------
Because "a wrong formula would agree with itself". Instead the layout is CROSS-
CHECKED against the Rust `write_section` byte-for-byte: this tool rebuilds a tiny
out-of-tree Rust crate that depends on the real `vmlm-core` with the real
`neuron-kv` feature and calls the real `neuron_kv::write_section`, then diffs the
result against the Python emitter. If that cross-check is unavailable the tool
still runs, but it prints CROSS-CHECK: SKIPPED and downgrades its own verdict --
it never silently substitutes "same constants, therefore same bytes".

Usage:
    python tools/p15_s5_section.py
"""
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

ROOT = str(Path(__file__).resolve().parents[1])
OUT_DIR = os.path.join(ROOT, "examples", "p15_s5")
SECTION_PATH = os.path.join(OUT_DIR, "neuron_kv_offsets.bin")
VMB_PATH = os.path.join(OUT_DIR, "neuron_kv.cache.vmb")
DUMP_PATH = os.path.join(OUT_DIR, "neuron_kv_offsets.dump.json")

FAILS = []


def check(name, ok, detail=""):
    tag = "PASS" if ok else "FAIL"
    print("  [%s] %s%s" % (tag, name, (" -- " + detail) if detail else ""))
    if not ok:
        FAILS.append(name)
    return ok


# ----------------------------------------------------------------------------
# 1. Geometry, taken from a REAL artifact on disk -- not from a docstring.
#
#    examples/minicpm_p13/meta.json is the 24-layer MiniCPM model that P13/P14
#    actually built and ran. Its kv_heads/head_dim are read here rather than
#    hardcoded, so if the artifact's geometry drifts, this tool fails loudly
#    instead of quietly emitting a section for a model that no longer exists.
# ----------------------------------------------------------------------------
def load_geometry_from_artifact():
    meta_path = os.path.join(ROOT, "examples", "minicpm_p13", "meta.json")
    if not os.path.isfile(meta_path):
        return None, meta_path
    with open(meta_path, "r", encoding="utf-8-sig") as f:
        meta = json.load(f)
    return meta, meta_path


# ----------------------------------------------------------------------------
# 2. The Rust-side constants. These are PARSED OUT OF core/src/format.rs rather
#    than retyped, so this file cannot drift from the shipped source silently.
# ----------------------------------------------------------------------------
def parse_rust_consts():
    src_path = os.path.join(ROOT, "core", "src", "format.rs")
    with open(src_path, "r", encoding="utf-8-sig") as f:
        text = f.read()
    lines = text.splitlines()
    want = {
        "SEC_NEURON_KV": "u32",
        "NKV_ENTRY": "usize",
        "NKV_HDR": "usize",
    }
    found = {}
    hits = {}
    for i, ln in enumerate(lines):
        s = ln.strip()
        if not s.startswith("pub const "):
            continue
        # NOTE: some of these constants carry a trailing `// comment` on the
        # same line (e.g. `pub const SEC_NEURON_KV: u32 = 1; // section tag...`).
        # The first version of this parser did not strip it and silently failed
        # to find SEC_NEURON_KV / NKV_ENTRY -- which is itself the kind of
        # "tool reported nothing" bug this project hard-fails on. The parse
        # failure is now reported as FAIL rather than degrading to a default.
        body = s.split("//", 1)[0].strip()
        for name, ty in want.items():
            if body.startswith("pub const %s:" % name) and ("%s =" % ty) in body:
                rhs = body.split("=", 1)[1].strip().rstrip(";").strip()
                try:
                    found[name] = int(rhs, 0)
                except ValueError:
                    continue
                hits[name] = (i + 1, s)
    return found, hits, src_path


# ----------------------------------------------------------------------------
# 3. The emitter: header + offsets, matching write_section() byte for byte.
#
#    write_section() (core/src/neuron_kv.rs:248-266) does:
#        put(0, n_layers) put(4, n_kv_heads) put(8, head_dim)
#        put(12, max_seq_per_neuron) put(16, stride)
#        for i in 0..n: put(NKV_HDR + i*NKV_ENTRY, i * stride)
#    i.e. little-endian u32 at those exact offsets.
#
#    `stride_mul_head_dim` is the S5-A BUG switch, and it exists ONLY so the
#    can-fail control can reproduce the real historical defect from the same
#    code path that produces the good bytes. It is not a supported option.
# ----------------------------------------------------------------------------
def build_section(n_layers, n_kv_heads, head_dim, max_seq_per_neuron, stride,
                  nkv_hdr=20, nkv_entry=4, stride_mul_head_dim=False):
    n_neurons = n_layers * n_kv_heads * head_dim
    hdr = struct.pack("<IIIII", n_layers, n_kv_heads, head_dim,
                      max_seq_per_neuron, stride)
    assert len(hdr) == nkv_hdr, "header size %d != NKV_HDR %d" % (len(hdr), nkv_hdr)
    out = bytearray(hdr)
    step = stride * head_dim if stride_mul_head_dim else stride
    for i in range(n_neurons):
        out.extend(struct.pack("<I", (i * step) & 0xFFFFFFFF))
    assert len(out) == nkv_hdr + n_neurons * nkv_entry
    return bytes(out), n_neurons


# ----------------------------------------------------------------------------
# 4. The RE-READ path. Parses the bytes BACK FROM DISK.
#
#    The truncation control (c) requires this to HARD-FAIL on a short file, so
#    every bounds condition raises instead of returning a short-but-valid
#    answer. This is the project's rule that illegal input must hard-fail:
#    a silently shortened offset array reads as "plausible-looking garbage".
# ----------------------------------------------------------------------------
class SectionError(Exception):
    pass


def read_section_from_disk(path, nkv_hdr=20, nkv_entry=4):
    if not os.path.isfile(path):
        raise SectionError("section file does not exist: %s" % path)
    size = os.path.getsize(path)
    if size < nkv_hdr:
        raise SectionError(
            "file is %d bytes, smaller than the %d-byte header -- refusing to "
            "parse a partial header out of a truncated file" % (size, nkv_hdr))
    with open(path, "rb") as f:
        blob = f.read()
    if len(blob) != size:
        raise SectionError("short read: expected %d bytes, got %d"
                           % (size, len(blob)))
    if size < nkv_hdr:
        raise SectionError("truncated header")
    n_layers, n_kv_heads, head_dim, max_seq, stride = struct.unpack_from(
        "<IIIII", blob, 0)
    n_neurons = n_layers * n_kv_heads * head_dim
    need = nkv_hdr + n_neurons * nkv_entry
    if size != need:
        raise SectionError(
            "size mismatch: file is %d bytes but the header declares %d neurons "
            "=> %d bytes required (header %d + %d*%d). Truncation or a wrong "
            "declared geometry -- NOT silently tolerated."
            % (size, n_neurons, need, nkv_hdr, n_neurons, nkv_entry))
    values = list(struct.unpack_from("<%dI" % n_neurons, blob, nkv_hdr))
    return {
        "n_layers": n_layers,
        "n_kv_heads": n_kv_heads,
        "head_dim": head_dim,
        "max_seq_per_neuron": max_seq,
        "stride": stride,
        "n_neurons": n_neurons,
        "n_entries": len(values),
        "values": values,
        "file_bytes": size,
    }


def count_offset_mismatches(parsed, stride_mul_head_dim=False):
    """Count entries that are NOT i*stride. Returns (mismatch_count, first_bad)."""
    stride = parsed["stride"]
    hd = parsed["head_dim"]
    step = stride * hd if stride_mul_head_dim else stride
    bad = 0
    first_bad = None
    for i, v in enumerate(parsed["values"]):
        want = (i * step) & 0xFFFFFFFF
        if v != want:
            bad += 1
            if first_bad is None:
                first_bad = {"i": i, "got": v, "want": want}
    return bad, first_bad


# ----------------------------------------------------------------------------
# 5. CROSS-CHECK against the real Rust write_section().
#
#    Builds a throwaway crate OUTSIDE the workspace (in TEMP) that path-depends
#    on vmlm-core with features=["neuron-kv"] and calls the shipped
#    unsafe fn write_section(&layout, dst). The crate is removed afterwards.
#
#    Why outside the workspace: a stray member inside <repo> could be
#    picked up by `cargo build` at the root and perturb the Lead's serialized
#    acceptance run. This tool must not be able to do that.
#
#    The harness prints the section as hex on stdout; we parse it. Note that the
#    engine/core crate is no_std, but vmlm-core builds fine as a plain rlib and
#    this little harness is a normal std binary, so no /ENTRY games are needed.
# ----------------------------------------------------------------------------
RUST_HARNESS = r'''
// Auto-generated throwaway cross-check: call the REAL neuron_kv::write_section.
use vmlm_core::neuron_kv::{write_section, NeuronKvLayout};

fn main() {
    let layout = NeuronKvLayout::tight(24, 2, 128, 1024);
    let n = layout.section_bytes();
    let mut buf = vec![0u8; n];
    let written = unsafe { write_section(&layout, buf.as_mut_ptr()) };
    println!("WRITTEN={}", written);
    println!("SECTION_BYTES={}", layout.section_bytes());
    println!("OFFSETS_BYTES={}", layout.offsets_bytes());
    println!("N_NEURONS={}", layout.n_neurons());
    // Print the full section as hex so the Python side can diff it byte-for-byte.
    let mut s = String::with_capacity(n * 2);
    for b in buf.iter() {
        s.push_str(&format!("{:02x}", b));
    }
    println!("HEX={}", s);
}
'''


def rust_crosscheck(python_bytes):
    """Return (status, detail). status in {OK, MISMATCH, SKIPPED}."""
    cargo = shutil.which("cargo")
    if cargo is None:
        return "SKIPPED", "cargo not on PATH"
    core_dir = os.path.join(ROOT, "core").replace("\\", "/")
    tmp = tempfile.mkdtemp(prefix="p15_s5_xcheck_")
    try:
        src_dir = os.path.join(tmp, "src")
        os.makedirs(src_dir)
        with open(os.path.join(tmp, "Cargo.toml"), "w", encoding="utf-8") as f:
            f.write(
                "[package]\n"
                'name = "p15_s5_xcheck"\n'
                'version = "0.0.0"\n'
                'edition = "2021"\n\n'
                "[dependencies]\n"
                'vmlm-core = { path = "%s", features = ["neuron-kv"] }\n\n'
                "[workspace]\n" % core_dir)
        with open(os.path.join(src_dir, "main.rs"), "w", encoding="utf-8") as f:
            f.write(RUST_HARNESS)
        p = subprocess.run([cargo, "run", "--release", "--quiet"],
                           cwd=tmp, capture_output=True, text=True,
                           errors="replace", timeout=600)
        if p.returncode != 0:
            tail = (p.stderr or "").strip().splitlines()[-6:]
            return "SKIPPED", "cargo run failed rc=%d: %s" % (
                p.returncode, " | ".join(tail))
        fields = {}
        for ln in (p.stdout or "").splitlines():
            if "=" in ln:
                k, v = ln.split("=", 1)
                fields[k.strip()] = v.strip()
        if "HEX" not in fields:
            return "SKIPPED", "harness produced no HEX line"
        rust_bytes = bytes.fromhex(fields["HEX"])
        if rust_bytes == python_bytes:
            return "OK", ("Rust write_section == Python emitter, %d bytes, "
                          "sha-equal; WRITTEN=%s N_NEURONS=%s OFFSETS_BYTES=%s"
                          % (len(rust_bytes), fields.get("WRITTEN"),
                             fields.get("N_NEURONS"),
                             fields.get("OFFSETS_BYTES")))
        # Locate the first differing byte -- the whole point is to say WHERE.
        n = min(len(rust_bytes), len(python_bytes))
        first = next((i for i in range(n) if rust_bytes[i] != python_bytes[i]), n)
        return "MISMATCH", ("first differing byte offset %d (rust len=%d, py len=%d)"
                            % (first, len(rust_bytes), len(python_bytes)))
    except Exception as e:  # noqa: BLE001 - a cross-check failure must not mask the rest
        return "SKIPPED", "%s: %s" % (type(e).__name__, e)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# ----------------------------------------------------------------------------
# 6. Dump helpers
# ----------------------------------------------------------------------------
def first_sorted_u32_offsets(blob, start_off, count):
    return list(struct.unpack_from("<%dI" % count, blob, start_off))


def main():
    print("=" * 72)
    print("P15 S5-W1: emit neuron_kv_offsets section -- host-side producer")
    print("=" * 72)

    # ---- 0. Rust constants, parsed from the shipped source -----------------
    print("\n=== 0. constants, parsed out of core/src/format.rs (not retyped) ===")
    consts, hits, fmt_path = parse_rust_consts()
    for name in ("SEC_NEURON_KV", "NKV_HDR", "NKV_ENTRY"):
        ln, txt = hits.get(name, (None, "NOT FOUND"))
        print("      %s = %s   <- %s:%s" % (name, consts.get(name), fmt_path, ln))
        print("         %s" % txt)
    ok_consts = all(n in consts for n in ("NKV_HDR", "NKV_ENTRY"))
    check("NKV_HDR parsed from format.rs", ok_consts and consts["NKV_HDR"] == 20,
          "NKV_HDR=%s" % consts.get("NKV_HDR"))
    check("NKV_ENTRY parsed from format.rs",
          ok_consts and consts["NKV_ENTRY"] == 4,
          "NKV_ENTRY=%s" % consts.get("NKV_ENTRY"))
    if not ok_consts:
        # Do NOT fall back to hardcoded defaults and carry on: that is exactly
        # the "probe silently measured nothing" failure mode. If the constants
        # cannot be read from the shipped source, this tool refuses to emit.
        print("\nABORT: could not parse NKV_HDR / NKV_ENTRY out of %s."
              % fmt_path)
        print("       Refusing to fall back to hardcoded defaults -- a producer "
              "whose constants are not traceable to format.rs is not evidence.")
        return 2
    nkv_hdr = consts["NKV_HDR"]
    nkv_entry = consts["NKV_ENTRY"]

    # ---- 1. geometry from a real artifact ---------------------------------
    print("\n=== 1. geometry, read from the real 24-layer MiniCPM artifact ===")
    meta, meta_path = load_geometry_from_artifact()
    if meta is None:
        print("      !! %s not found" % meta_path)
        return 2
    NL = int(meta["layers"])
    NKH = int(meta["kv_heads"])
    HD = int(meta["head_dim"])
    print("      source: %s" % meta_path)
    print("      layers=%d kv_heads=%d head_dim=%d hidden=%d heads=%d inter=%d vocab=%d"
          % (NL, NKH, HD, meta["hidden"], meta["heads"], meta["inter"],
             meta["vocab"]))
    check("artifact is the 24-layer MiniCPM geometry the brief names",
          (NL, NKH, HD) == (24, 2, 128), "got (%d,%d,%d)" % (NL, NKH, HD))

    # ---- 2. the arithmetic, printed ---------------------------------------
    PMAX = 1024
    stride = PMAX                       # tight(): stride == max_seq_per_neuron
    n_neurons = NL * NKH * HD
    offsets_bytes = n_neurons * nkv_entry
    section_bytes = nkv_hdr + offsets_bytes

    print("\n=== 2. the arithmetic (MEASURE: every term printed) ===")
    print("      n_neurons      = n_layers * n_kv_heads * head_dim")
    print("                     = %d * %d * %d = %d" % (NL, NKH, HD, n_neurons))
    print("      max_seq_per_neuron (PMAX) = %d" % PMAX)
    print("      stride (tight() = PMAX)   = %d" % stride)
    print("      offsets_bytes  = n_neurons * NKV_ENTRY = %d * %d = %d"
          % (n_neurons, nkv_entry, offsets_bytes))
    print("      section_bytes  = NKV_HDR + offsets_bytes = %d + %d = %d"
          % (nkv_hdr, offsets_bytes, section_bytes))
    print("      last entry i=%d -> value %d (u32 max %d, fits: %s)"
          % (n_neurons - 1, (n_neurons - 1) * stride, 0xFFFFFFFF,
             (n_neurons - 1) * stride <= 0xFFFFFFFF))
    print("      total element span = n_neurons * stride = %d elements"
          % (n_neurons * stride))
    print("      (stride=HD*PMAX would be %d -> the 128x S5-A bug, %.2f GB vs %.2f GB)"
          % (HD * PMAX, n_neurons * HD * PMAX * 4 / 1e9, n_neurons * stride * 4 / 1e9))
    check("n_neurons == 6144", n_neurons == 6144, "%d" % n_neurons)
    check("stride == PMAX == 1024 (tight, NOT HD*PMAX)", stride == PMAX,
          "%d" % stride)
    check("section_bytes == 24596", section_bytes == 24596, "%d" % section_bytes)

    # ---- 3. emit ----------------------------------------------------------
    print("\n=== 3. EMIT the section (this is the producer that did not exist) ===")
    if not os.path.isdir(OUT_DIR):
        os.makedirs(OUT_DIR)
        print("      created %s" % OUT_DIR)
    blob, _n = build_section(NL, NKH, HD, PMAX, stride, nkv_hdr, nkv_entry)
    with open(SECTION_PATH, "wb") as f:
        f.write(blob)
    on_disk = os.path.getsize(SECTION_PATH)
    print("      wrote %s" % SECTION_PATH)
    print("      len(emitted bytes) = %d" % len(blob))
    print("      os.path.getsize     = %d" % on_disk)
    check("emitted byte length == section_bytes arithmetic",
          len(blob) == section_bytes, "%d vs %d" % (len(blob), section_bytes))
    check("file on disk is exactly %d bytes" % section_bytes,
          on_disk == section_bytes, "measured %d B" % on_disk)

    # header bytes, spelled out so the layout is not taken on faith
    print("      header bytes [0..%d):" % nkv_hdr)
    for off, name, val in ((0, "n_layers", NL), (4, "n_kv_heads", NKH),
                           (8, "head_dim", HD),
                           (12, "max_seq_per_neuron", PMAX),
                           (16, "stride", stride)):
        raw = blob[off:off + 4]
        print("        [%2d] u32 %-19s = %-6d bytes %s"
              % (off, name, val, raw.hex(" ")))
    print("      first 4 entries at [%d..]: %s"
          % (nkv_hdr, first_sorted_u32_offsets(blob, nkv_hdr, 4)))
    last_off = nkv_hdr + (n_neurons - 4) * nkv_entry
    print("      last  4 entries at [%d..]: %s"
          % (last_off, first_sorted_u32_offsets(blob, last_off, 4)))

    # Also emit a .vmb-like blob so a later consumer has something to load.
    #
    # HONEST NOTE: the 32-byte .vmb header (interp.rs:127-142) has NO section
    # table -- it is magic/version, text_off/len, const_off/len, meta_off/len.
    # SEC_NEURON_KV is defined in format.rs:284 but nothing in the loader reads a
    # section tag. So there is nowhere in the EXISTING container to put this
    # without changing the loader, which is outside this task's write scope.
    # The .vmb-like file below is therefore the real 32-byte header plus a
    # 16-byte trailer that names the section (tag, offset, length, 0) followed by
    # the section bytes. It is explicitly NOT loadable by today's engine, and is
    # labelled as such in the sidecar. The standalone .bin is the load-bearing
    # artifact; the trailer is a forward-compatible sketch, not a claim.
    SECTION_TRAILER = 16
    trailer_off = 32
    section_off = trailer_off + SECTION_TRAILER
    vmb = bytearray()
    vmb.extend(struct.pack("<IHH", 0x4D4C4D56, 1, 0))          # magic, version, pad
    vmb.extend(struct.pack("<IIIIII", 0, 0, 0, 0, 0, 0))       # empty text/const/meta
    vmb.extend(struct.pack("<IIII", consts.get("SEC_NEURON_KV", 1),
                           section_off, section_bytes, 0))
    vmb.extend(blob)
    with open(VMB_PATH, "wb") as f:
        f.write(vmb)
    print("      wrote %s (%d bytes: 32 B real header + %d B section trailer "
          "+ %d B section)" % (VMB_PATH, len(vmb), SECTION_TRAILER, section_bytes))
    print("      ^ NOT loadable by today's engine: the 32-byte header has no "
          "section table (interp.rs:127-142).")
    with open(VMB_PATH, "rb") as f:
        back = f.read()
    check("the .vmb-like blob carries the section bytes verbatim at offset %d"
          % section_off, back[section_off:] == blob,
          "%d B round-tripped" % (len(back) - section_off))

    # ---- 4. RE-READ from disk, and check --------------------------------
    print("\n=== 4. RE-READ the bytes back from disk and check every entry ===")
    parsed = read_section_from_disk(SECTION_PATH)
    print("      file_bytes      = %d" % parsed["file_bytes"])
    print("      parsed n_layers = %d" % parsed["n_layers"])
    print("      parsed n_kv_heads=%d" % parsed["n_kv_heads"])
    print("      parsed head_dim = %d" % parsed["head_dim"])
    print("      parsed max_seq  = %d" % parsed["max_seq_per_neuron"])
    print("      parsed stride   = %d" % parsed["stride"])
    print("      parsed n_neurons= %d" % parsed["n_neurons"])
    print("      parsed n_entries= %d" % parsed["n_entries"])
    hdr_roundtrip = (parsed["n_layers"] == NL and parsed["n_kv_heads"] == NKH
                     and parsed["head_dim"] == HD
                     and parsed["max_seq_per_neuron"] == PMAX
                     and parsed["stride"] == stride)
    check("header round-trips exactly", hdr_roundtrip,
          "(%d,%d,%d,%d,%d)" % (parsed["n_layers"], parsed["n_kv_heads"],
                                parsed["head_dim"], parsed["max_seq_per_neuron"],
                                parsed["stride"]))
    check("parsed n_entries == %d" % n_neurons,
          parsed["n_entries"] == n_neurons, "%d" % parsed["n_entries"])
    bad, first_bad = count_offset_mismatches(parsed)
    print("      consistency: entries != i*stride -> %d mismatches" % bad)
    check("every entry == i*stride (0 mismatches)", bad == 0,
          "%d mismatches%s" % (bad, "" if bad == 0 else ", first=%s" % first_bad))
    check("invariant max_seq_per_neuron <= stride holds",
          parsed["max_seq_per_neuron"] <= parsed["stride"],
          "%d <= %d" % (parsed["max_seq_per_neuron"], parsed["stride"]))

    # ---- 5. CAN-FAIL CONTROLS -------------------------------------------
    print("\n" + "=" * 72)
    print("=== 5. CAN-FAIL CONTROLS (each must FAIL; counts, not booleans) ===")
    print("=" * 72)

    # (a) re-inject the S5-A 128x bug: entry[i] = i*head_dim*stride
    print("\n-- control (a): entry[i] = i * head_dim * stride  (the 128x S5-A bug) --")
    bug_blob, _ = build_section(NL, NKH, HD, PMAX, stride, nkv_hdr, nkv_entry,
                                stride_mul_head_dim=True)
    bug_path = os.path.join(OUT_DIR, "_control_a_head_dim_bug.bin")
    with open(bug_path, "wb") as f:
        f.write(bug_blob)
    print("      wrote %s (%d bytes)" % (bug_path, os.path.getsize(bug_path)))
    p_a = read_section_from_disk(bug_path)
    bad_a, first_a = count_offset_mismatches(p_a)
    print("      entries != i*stride -> %d mismatches (must be > 0)" % bad_a)
    print("      first bad: %s" % first_a)
    check("control (a) REJECTED: the consistency check reports FAIL",
          bad_a > 0, "%d/%d mismatches" % (bad_a, p_a["n_entries"]))
    check("control (a) also differs from the good bytes",
          bug_blob != blob,
          "%d differing byte positions"
          % sum(1 for x, y in zip(bug_blob, blob) if x != y))
    print("      (entry[0] is 0 under both formulas, so exactly entries 1..%d "
          "move -- hence %d, not %d)" % (n_neurons - 1, bad_a, n_neurons))

    # (b) flip the stride header field -> parse-back must FAIL
    print("\n-- control (b): flip the stride header field, keep the payload --")
    flip_blob = bytearray(blob)
    struct.pack_into("<I", flip_blob, 16, stride + 1)
    flip_path = os.path.join(OUT_DIR, "_control_b_stride_flip.bin")
    with open(flip_path, "wb") as f:
        f.write(bytes(flip_blob))
    print("      header stride field patched to %d at byte offset 16" % (stride + 1))
    p_b = read_section_from_disk(flip_path)
    bad_b, first_b = count_offset_mismatches(p_b)
    print("      parsed stride = %d" % p_b["stride"])
    print("      entries != i*stride -> %d mismatches (must be > 0)" % bad_b)
    print("      first bad: %s" % first_b)
    check("control (b) REJECTED: parse-back reports FAIL after the stride flip",
          bad_b > 0, "%d/%d mismatches" % (bad_b, p_b["n_entries"]))
    check("control (b) stride field really changed on disk",
          p_b["stride"] != stride, "%d != %d" % (p_b["stride"], stride))
    # And a control-on-the-control: flipping the LAST header word only is the
    # kind of edit that a header-agnostic reader would miss. Confirm it is seen.
    check("control (b) mismatch count is one-per-nonzero-entry, not just entry 0",
          bad_b == n_neurons - 1, "%d (expected %d)" % (bad_b, n_neurons - 1))

    # (c) truncate the file by 4 bytes -> read must HARD-FAIL
    print("\n-- control (c): truncate the file by 4 bytes --")
    trunc_path = os.path.join(OUT_DIR, "_control_c_truncated_by_4.bin")
    with open(trunc_path, "wb") as f:
        f.write(blob[:-4])
    tsize = os.path.getsize(trunc_path)
    print("      wrote %s (%d bytes = %d - 4)" % (trunc_path, tsize, section_bytes))
    hard_failed = False
    fail_msg = ""
    try:
        p_c = read_section_from_disk(trunc_path)
        print("      !! read SUCCEEDED with %d entries -- that is the silent "
              "shortening this control exists to catch" % p_c["n_entries"])
    except SectionError as e:
        hard_failed = True
        fail_msg = str(e)
        print("      SectionError raised (hard fail, rc=2 semantics): %s" % fail_msg)
    check("control (c) REJECTED: truncated read HARD-FAILS instead of shortening",
          hard_failed, fail_msg if hard_failed else "read returned instead")
    # Show it would have silently produced a plausible-looking short section.
    naive_entries = (tsize - nkv_hdr) // nkv_entry
    print("      a naive reader would have returned %d entries (real %d) and "
          "reported 'OK' -- that is the silent-degradation class this project "
          "hard-fails on" % (naive_entries, n_neurons))

    # (d) extra control not required by the brief: an all-zero payload.
    #     Guards against "the check passes because everything is 0".
    print("\n-- control (d) [extra]: zeroed payload, correct header --")
    zero_path = os.path.join(OUT_DIR, "_control_d_zero_payload.bin")
    with open(zero_path, "wb") as f:
        f.write(blob[:nkv_hdr] + b"\x00" * (section_bytes - nkv_hdr))
    p_d = read_section_from_disk(zero_path)
    bad_d, _ = count_offset_mismatches(p_d)
    print("      entries != i*stride -> %d mismatches (must be > 0)" % bad_d)
    check("control (d) REJECTED: an all-zero payload is caught",
          bad_d > 0, "%d/%d mismatches" % (bad_d, p_d["n_entries"]))

    # ---- 6. Rust cross-check --------------------------------------------
    print("\n=== 6. CROSS-CHECK against the real Rust write_section() ===")
    print("      building a throwaway out-of-tree crate that path-depends on")
    print("      vmlm-core with features=[\"neuron-kv\"] and calls the shipped")
    print("      neuron_kv::write_section, then diffing its bytes against ours.")
    status, detail = rust_crosscheck(blob)
    print("      CROSS-CHECK: %s -- %s" % (status, detail))
    check("Rust write_section output == Python emitter output (byte-for-byte)",
          status == "OK", "%s: %s" % (status, detail))

    # ---- 7. determinism --------------------------------------------------
    print("\n=== 7. determinism: re-emit and compare ===")
    blob2, _ = build_section(NL, NKH, HD, PMAX, stride, nkv_hdr, nkv_entry)
    check("re-emitting the same geometry is byte-identical", blob2 == blob,
          "%d bytes" % len(blob2))
    with open(SECTION_PATH, "rb") as f:
        reread = f.read()
    check("the file on disk still equals the emitted bytes", reread == blob,
          "%d bytes" % len(reread))

    # ---- 8. sidecar dump -------------------------------------------------
    print("\n=== 8. sidecar dump ===")
    dump = {
        "section": "neuron_kv_offsets",
        "tag_SEC_NEURON_KV": consts.get("SEC_NEURON_KV"),
        "geometry": {"n_layers": NL, "n_kv_heads": NKH, "head_dim": HD,
                     "max_seq_per_neuron": PMAX, "stride": stride,
                     "n_neurons": n_neurons},
        "sizes": {"NKV_HDR": nkv_hdr, "NKV_ENTRY": nkv_entry,
                  "offsets_bytes": offsets_bytes,
                  "section_bytes": section_bytes},
        "layout": "header u32 x5 LE, then n_neurons u32 LE; entry[i] == i*stride",
        "header_offsets": {"n_layers": 0, "n_kv_heads": 4, "head_dim": 8,
                           "max_seq_per_neuron": 12, "stride": 16},
        "provenance": {
            "geometry_source": meta_path,
            "constant_source": fmt_path,
            "rust_api": "core/src/neuron_kv.rs::write_section",
            "rust_crosscheck": status,
            "rust_crosscheck_detail": detail,
        },
        "honest_limits": [
            "HOST-SIDE tooling: costs the ENGINE 0 bytes; no core/asm/runtime source touched.",
            "Does NOT make S5 end-to-end: the engine still has no call site that reads this section.",
            "The 32-byte .vmb header has no section table; neuron_kv.cache.vmb is NOT engine-loadable.",
            "n_neurons*stride element span is arithmetic, not a measured allocation (no path allocates it).",
        ],
        "first_4_offsets": parsed["values"][:4],
        "last_4_offsets": parsed["values"][-4:],
        "mismatches_on_reparse": bad,
    }
    with open(DUMP_PATH, "w", encoding="utf-8") as f:
        json.dump(dump, f, indent=2)
    print("      wrote %s" % DUMP_PATH)

    # ---- verdict ---------------------------------------------------------
    print("\n" + "=" * 72)
    if FAILS:
        print("VERDICT: FAIL -- %d check(s) failed:" % len(FAILS))
        for f_ in FAILS:
            print("   - %s" % f_)
        return 1
    print("VERDICT: PASS -- the neuron index now EXISTS ON DISK.")
    print("  section file : %s" % SECTION_PATH)
    print("  measured size: %d bytes (header %d + %d neurons * %d B)"
          % (on_disk, nkv_hdr, n_neurons, nkv_entry))
    print("  re-parse     : %d entries, %d mismatches vs i*stride"
          % (parsed["n_entries"], bad))
    print("  can-fail     : (a) head_dim bug %d mismatches | (b) stride flip %d "
          "mismatches | (c) truncation hard-failed=%s | (d) zero payload %d "
          "mismatches" % (bad_a, bad_b, hard_failed, bad_d))
    print("  engine cost  : 0 bytes (host-side Python; nothing linked into the engine)")
    print("  STILL UNVERIFIED: the engine has no call site that consumes this")
    print("    section (no load-time reorder). S5 end-to-end remains UNVERIFIED;")
    print("    what is now verified is that the index is a real disk artifact.")
    return 0


