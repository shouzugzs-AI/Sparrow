#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
P10 B2: build a real MiniCPM5-1B **layer 0** .vml + weights, run the actual
VMLM engine, and diff every stage against the HuggingFace capture.

GOAL (per the task brief): not to "make it run", but to **expose every real
gap** in the engine with one end-to-end comparison. `minicpm_layer0_check_ref.py`
already proved the numpy decomposition matches HF to ~1e-6, so any mismatch
here is an ENGINE gap, not a misunderstanding of the layer.

Design notes that matter:
  * Sequence length 4 (tiny on purpose) so a layer is affordable in the
    interpreter and every stage is diffable.
  * RoPE is applied with a **precomputed sin/cos constant table** dumped from
    HF's own rotary embedding -- this deliberately sidesteps the missing RoPE
    opcode so that the rest of the layer can still be validated. That is the
    staging the task brief asked for.
  * Weights are written as .bin (f32) via the same convention as
    tools/asm_all.ps1, and assembled through vmlm-asm with explicit
    name:file:rows:cols, so the shapes can never silently drift.

Usage:
    python tools/minicpm_layer0_vml.py            # build + assemble + run
"""

import json
import os
import subprocess
import sys

import numpy as np

REF = r"<repo>/examples/minicpm/layer0_ref"
OUT = r"<repo>/examples/minicpm"
ASM = r"<repo>/target/release/vmlm-asm.exe"
ENG = r"<repo>/target/release/vmlm-runtime.exe"


def L(name):
    return np.load(os.path.join(REF, name + ".npy")).astype(np.float32)


def wr(name, arr):
    """Write a f32 .bin in the shape convention the assembler expects."""
    arr = np.ascontiguousarray(arr, dtype=np.float32)
    p = os.path.join(OUT, name + ".bin")
    arr.tofile(p)
    return name, arr.shape


def main():
    os.makedirs(OUT, exist_ok=True)
    meta = json.load(open(os.path.join(REF, "meta.json"), encoding="utf-8"))
    cfg = meta["config"]
    H, I = cfg["hidden_size"], cfg["intermediate_size"]
    nh, nkv, hd = cfg["num_attention_heads"], cfg["num_key_value_heads"], cfg["head_dim"]
    S = meta["seq"]
    eps = cfg["rms_norm_eps"]

    print("MiniCPM5-1B layer 0 -> VMLM")
    print("  H=%d I=%d nh=%d nkv=%d hd=%d S=%d eps=%g" % (H, I, nh, nkv, hd, S, eps))

    # ------------------------------------------------------------- weights
    consts = []
    consts.append(wr("h_in", L("hidden_in")[0]))                   # [S,H]
    consts.append(wr("g_in", L("input_layernorm_weight")))         # [H]
    consts.append(wr("Wq", L("self_attn_q_proj_weight")))          # [nh*hd,H]
    consts.append(wr("Wk", L("self_attn_k_proj_weight")))          # [nkv*hd,H]
    consts.append(wr("Wv", L("self_attn_v_proj_weight")))          # [nkv*hd,H]
    consts.append(wr("Wo", L("self_attn_o_proj_weight")))          # [H,nh*hd]
    consts.append(wr("g_post", L("post_attention_layernorm_weight")))
    consts.append(wr("Wg", L("mlp_gate_proj_weight")))             # [I,H]
    consts.append(wr("Wu", L("mlp_up_proj_weight")))               # [I,H]
    consts.append(wr("Wd", L("mlp_down_proj_weight")))             # [H,I]
    consts.append(wr("cos", L("rope_cos")))                        # [S,hd]
    consts.append(wr("sin", L("rope_sin")))                        # [S,hd]
    consts.append(wr("eps", np.array([eps], dtype=np.float32)))

    # --------------------------------------------------------- .vml script
    # Delegation order follows the engine's operand convention:
    #   GEMM dst, a, b     -> dst[M,N] = a[M,K] . b[N,K]^T   (NT, weights [N,K])
    #   GEMM dst, a, b, nn -> dst[M,N] = a[M,K] . b[K,N]     (NN)
    #   RMSNORM dst, src, gamma, eps
    #
    # The attention is written per-head (16 heads) because there is no
    # batched GQA head loop in the ISA yet -- SEE gaps report.
    vml = []
    A = vml.append
    A("; MiniCPM5-1B layer 0 (generated by tools/minicpm_layer0_vml.py)")
    A("; S=%d H=%d I=%d nh=%d nkv=%d hd=%d" % (S, H, I, nh, nkv, hd))
    A("")
    A("; ---- shapes ----")
    A("SHAPE h_in,  %d, %d" % (S, H))
    A("SHAPE g_in,  1, %d" % H)
    A("SHAPE Wq,    %d, %d" % (nh * hd, H))
    A("SHAPE Wk,    %d, %d" % (nkv * hd, H))
    A("SHAPE Wv,    %d, %d" % (nkv * hd, H))
    A("SHAPE Wo,    %d, %d" % (H, nh * hd))
    A("SHAPE cos,   %d, %d" % (S, hd))
    A("SHAPE sin,   %d, %d" % (S, hd))
    A("SHAPE eps,   1, 1")
    A("")
    A("; ---- [1] input RMSNorm ----")
    A("SHAPE xn,    %d, %d" % (S, H))
    A("RMSNORM xn, h_in, g_in, eps")
    A("")
    A("; ---- [2] q/k/v projections ----")
    A("SHAPE q,     %d, %d" % (S, nh * hd))
    A("SHAPE k,     %d, %d" % (S, nkv * hd))
    A("SHAPE v,     %d, %d" % (S, nkv * hd))
    A("GEMM q, xn, Wq")
    A("GEMM k, xn, Wk")
    A("GEMM v, xn, Wv")
    A("")

    # ---- [3] RoPE + [4] attention, unrolled per head ----
    # q head h occupies columns [h*hd, (h+1)*hd) of q.
    # k/v head j occupies columns [j*hd, (j+1)*hd), and head h uses kv head
    # j = h // (nh/nkv)   <- this is the GQA mapping.
    rep = nh // nkv
    A("; ---- [3]+[4] per-head RoPE (precomputed table) + GQA attention ----")
    A("SHAPE att_out, %d, %d" % (S, nh * hd))
    # Accumulate each head's context into att_out via WRITECOL.
    # scratch slots (per-head, must be distinct -- see P9 contract 5.0d:
    # reusing one work slot across heads is a silent-degradation trap).
    A("SHAPE qh,    %d, %d" % (S, hd))
    A("SHAPE kh,    %d, %d" % (S, hd))
    A("SHAPE vh,    %d, %d" % (S, hd))
    A("SHAPE q1,    %d, %d" % (S, hd // 2))
    A("SHAPE q2,    %d, %d" % (S, hd // 2))
    A("SHAPE c1,    %d, %d" % (S, hd // 2))
    A("SHAPE c2,    %d, %d" % (S, hd // 2))
    A("SHAPE s1,    %d, %d" % (S, hd // 2))
    A("SHAPE s2,    %d, %d" % (S, hd // 2))
    A("SHAPE o1,    %d, %d" % (S, hd // 2))
    A("SHAPE o2,    %d, %d" % (S, hd // 2))
    A("SHAPE qrot,  %d, %d" % (S, hd))
    A("SHAPE krot,  %d, %d" % (S, hd))
    # half-width scratch for the RoPE products. NOTE: must be its OWN slot
    # with the RIGHT width -- reusing `krot` (declared [S,hd]) for a [S,hd/2]
    # product trips the engine's EW shape check (exit 8). That check firing
    # is a GOOD outcome: it is exactly the "shape errors DO report" case
    # from white paper 15.5, as opposed to the silent slot-overwrite kind.
    A("SHAPE tmpsc,  %d, %d" % (S, hd // 2))
    A("SHAPE sc,    %d, %d" % (S, S))
    A("SHAPE ctx,   %d, %d" % (S, hd))

    # cos/sin halves are shared across heads -> slice once, outside the loop
    A("SLICE c1, cos, 0, %d" % (hd // 2))
    A("SLICE c2, cos, %d, %d" % (hd // 2, hd // 2))
    A("SLICE s1, sin, 0, %d" % (hd // 2))
    A("SLICE s2, sin, %d, %d" % (hd // 2, hd // 2))
    A("")

    for h in range(nh):
        j = h // rep
        A("; ---- head %d (kv head %d) ----" % (h, j))
        A("SLICE qh, q, %d, %d" % (h * hd, hd))
        A("SLICE kh, k, %d, %d" % (j * hd, hd))
        A("SLICE vh, v, %d, %d" % (j * hd, hd))
        # rotate_half in half-split form:
        #   q1 = qh[:, :hd/2] ; q2 = qh[:, hd/2:]
        #   o1 = q1*c1 - q2*s1 ; o2 = q1*s1 + q2*c2   (c2 == c1 here, but
        #   keeping them separate documents the convention)
        A("SLICE q1, qh, 0, %d" % (hd // 2))
        A("SLICE q2, qh, %d, %d" % (hd // 2, hd // 2))
        A("EWMUL o1, q1, c1")
        A("EWMUL tmpsc, q2, s1")
        A("EWSUB o1, o1, tmpsc")
        A("EWMUL o2, q1, s1")
        A("EWMUL tmpsc, q2, c2")
        A("EWADD o2, o2, tmpsc")
        A("CONCAT qrot, o1, o2")
        # same for k
        A("SLICE q1, kh, 0, %d" % (hd // 2))
        A("SLICE q2, kh, %d, %d" % (hd // 2, hd // 2))
        A("EWMUL o1, q1, c1")
        A("EWMUL tmpsc, q2, s1")
        A("EWSUB o1, o1, tmpsc")
        A("EWMUL o2, q1, s1")
        A("EWMUL tmpsc, q2, c2")
        A("EWADD o2, o2, tmpsc")
        A("CONCAT krot, o1, o2")
        # scores: sc[S,S] = qrot @ krot^T.
        #   NT (the DEFAULT) treats B as [N,K]; with krot=[S,hd] that gives
        #   N = rows(krot) = S. Correct.
        #   `nn` would treat B as [K,N] => N = cols(krot) = hd = 128 and
        #   OVERRUN the [S,S] destination (engine has no capacity guard on
        #   GEMM output -- it segfaults instead). See gaps report.
        A("GEMM sc, qrot, krot")
        A("SCALE sc, sc, inv_sqrt_hd")
        A("SOFTMAX sc, sc, causal")
        # ctx[S,hd] = att[S,S] @ vh[S,hd]: here B realy is [K,N] -> NN.
        A("GEMM ctx, sc, vh, nn")
        A("WRITECOL att_out, ctx, %d, %d" % (h * hd, hd))
        A("")

    consts.append(wr("inv_sqrt_hd", np.array([1.0 / np.sqrt(hd)], dtype=np.float32)))

    A("; ---- [5] o_proj + residual ----")
    A("SHAPE oproj, %d, %d" % (S, H))
    A("GEMM oproj, att_out, Wo")
    A("SHAPE h1,    %d, %d" % (S, H))
    A("EWADD h1, h_in, oproj")
    A("")
    A("; ---- [6] post RMSNorm + SwiGLU MLP ----")
    A("SHAPE xn2,   %d, %d" % (S, H))
    A("RMSNORM xn2, h1, g_post, eps")
    A("SHAPE gate,  %d, %d" % (S, I))
    A("SHAPE up,    %d, %d" % (S, I))
    A("GEMM gate, xn2, Wg")
    A("GEMM up, xn2, Wu")
    A("SHAPE acts,  %d, %d" % (S, I))
    A("ACT acts, gate, silu")
    A("EWMUL acts, acts, up")
    A("SHAPE down,  %d, %d" % (S, H))
    A("GEMM down, acts, Wd")
    A("")
    A("; ---- [7] output ----")
    A("SHAPE h_out, %d, %d" % (S, H))
    A("EWADD h_out, h1, down")
    A("")
    A("; ---- dumps for stage-by-stage diff ----")
    A("PRINT xn")
    A("PRINT q")
    A("PRINT k")
    A("PRINT v")
    A("PRINT att_out")
    A("PRINT oproj")
    A("PRINT xn2")
    A("PRINT gate")
    A("PRINT acts")
    A("PRINT down")
    A("PRINT h_out")
    A("HALT")

    vml_path = os.path.join(OUT, "layer0.vml")
    # Write WITHOUT a BOM: PowerShell's Out-File -Encoding utf8 adds one and
    # the assembler then reports "unknown instruction" (documented P9 trap).
    with open(vml_path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(vml) + "\n")
    print("wrote %s (%d lines)" % (vml_path, len(vml)))

    # ------------------------------------------------------------- assemble
    vmb = os.path.join(OUT, "layer0.vmb")
    args = [ASM, "layer0.vml", "layer0.vmb"]
    for name, shape in consts:
        if len(shape) == 1:
            args.append("%s:%s.bin:1:%d" % (name, name, shape[0]))
        else:
            args.append("%s:%s.bin:%d:%d" % (name, name, shape[0], shape[1]))
    r = subprocess.run(args, cwd=OUT, capture_output=True, text=True,
                       errors="replace", encoding="utf-8")
    # The assembler prints a UTF-8 warning glyph; under a GBK console that
    # raises UnicodeEncodeError on print(). Encode defensively.
    def _p(s):
        try:
            print(s)
        except UnicodeEncodeError:
            print(s.encode("ascii", "replace").decode("ascii"))

    _p(r.stdout.strip())
    if r.returncode != 0:
        _p("ASSEMBLE FAILED:\n%s" % r.stderr)
        return 1

    print("\nassembled -> %s" % vmb)
    return 0


if __name__ == "__main__":
    sys.exit(main())
